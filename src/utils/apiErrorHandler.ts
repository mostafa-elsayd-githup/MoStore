import type { ApiError } from "../types/AuthTypes/AuthFormType";

const ERROR_MESSAGES_MAP: Record<number, string> = {
  400: "البريد الإلكتروني أو كلمة المرور غير صحيحة",
  401: "غير مصرح لك، يرجى تسجيل الدخول مرة أخرى",
  403: "عذراً، لا تملك الصلاحية للقيام بهذا الإجراء",
  404: "الخدمة المطلوبة غير موجودة حالياً",
  409: "هذا الحساب أو البريد الإلكتروني موجود بالفعل",
  422: "البريد الإلكتروني مسجل مسبقاً أو أن البيانات المدخلة غير صالحة",
  429: "لقد تجاوزت الحد المسموح من المحاولات، يرجى الانتظار قليلاً",
  500: "حدث خطأ في الخادم الداخلي، نحن نعمل على إصلاحه",
  502: "بوابة غير صالحة أو مشكلة مؤقتة في الشبكة",
  503: "الخدمة غير متاحة حالياً، يرجى المحاولة لاحقاً",
};

export const getFriendlyErrorMessage = (error: ApiError): string => {
  const statusCode = Number(error?.status || 400);
  return (
    ERROR_MESSAGES_MAP[statusCode] ||
    error?.message ||
    "حدث خطأ غير متوقع، يرجى المحاولة لاحقاً"
  );
};
